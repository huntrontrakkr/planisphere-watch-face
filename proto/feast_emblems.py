def emblem(name, night=None):
    """An emblem as a boolean array; the Hanukkah lamp with tonight's lights (night 1-8, from the right, as the
    candles are set) over its eight candles, and the shammash raised in the middle, always lit."""
    a = np.array([[c == "#" for c in r] for r in EMBLEMS[name]])
    if name == "hanukkiah":
        top = np.zeros((2, a.shape[1]), bool)
        top[0, 4] = top[1, 4] = True                       # the shammash, a candle taller, and its flame
        for x in [8, 7, 6, 5, 3, 2, 1, 0][:night or 0]:
            top[1, x] = True                               # tonight's flames
        a = np.vstack([top, a])
    return a
