"""The Moon and the Sun to the precision eclipses need: the Moon from Meeus's truncated ELP-2000/82 series
(Astronomical Algorithms, ch. 47: about 10 arcseconds), the Sun from his solar theory (ch. 25: about 0.01 degree,
with the aberration), both in dynamical time (TT = UT + delta T). Angles in degrees."""
import math

D2R = math.pi / 180


def sind(a): return math.sin(a * D2R)
def cosd(a): return math.cos(a * D2R)


def delta_t(year):
    """TT - UT in seconds: about 69 s through these decades (the Earth's rotation has held steady)."""
    return 69.2 + 0.25 * (year - 2025)


