def moon(jde):
    """Geocentric ecliptic longitude and latitude of date (degrees, without nutation) and distance (km)."""
    T = (jde - 2451545.0) / 36525
    Lp = 218.3164477 + 481267.88123421 * T - 0.0015786 * T ** 2 + T ** 3 / 538841 - T ** 4 / 65194000
    D = 297.8501921 + 445267.1114034 * T - 0.0018819 * T ** 2 + T ** 3 / 545868 - T ** 4 / 113065000
    M = 357.5291092 + 35999.0502909 * T - 0.0001536 * T ** 2 + T ** 3 / 24490000
    Mp = 134.9633964 + 477198.8675055 * T + 0.0087414 * T ** 2 + T ** 3 / 69699 - T ** 4 / 14712000
    F = 93.2720950 + 483202.0175233 * T - 0.0036539 * T ** 2 - T ** 3 / 3526000 + T ** 4 / 863310000
    A1, A2, A3 = 119.75 + 131.849 * T, 53.09 + 479264.290 * T, 313.45 + 481266.484 * T
    E = 1 - 0.002516 * T - 0.0000074 * T ** 2
    sl = sr = sb = 0.0
    for d, m, mp, f, cl, cr in _LR:
        e = E ** abs(m)
        arg = d * D + m * M + mp * Mp + f * F
        sl += cl * e * sind(arg)
        sr += cr * e * cosd(arg)
    for d, m, mp, f, cb in _B:
        sb += cb * E ** abs(m) * sind(d * D + m * M + mp * Mp + f * F)
    sl += 3958 * sind(A1) + 1962 * sind(Lp - F) + 318 * sind(A2)
    sb += (-2235 * sind(Lp) + 382 * sind(A3) + 175 * sind(A1 - F) + 175 * sind(A1 + F) + 127 * sind(Lp - Mp)
           - 115 * sind(Lp + Mp))
    return (Lp + sl / 1e6) % 360, sb / 1e6, 385000.56 + sr / 1000


def sun(jde):
    """The Sun's apparent ecliptic longitude of date (degrees, with the aberration, without nutation) and its
    distance (AU)."""
    T = (jde - 2451545.0) / 36525
    L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T ** 2
    M = 357.52911 + 35999.05029 * T - 0.0001537 * T ** 2
    e = 0.016708634 - 0.000042037 * T - 0.0000001267 * T ** 2
    C = ((1.914602 - 0.004817 * T - 0.000014 * T ** 2) * sind(M) + (0.019993 - 0.000101 * T) * sind(2 * M)
         + 0.000289 * sind(3 * M))
    true_lon, v = L0 + C, M + C
    R = 1.000001018 * (1 - e * e) / (1 + e * cosd(v))
    return (true_lon - 0.00569) % 360, R


def nutation(jde):
    """Nutation in longitude and the true obliquity (degrees), to the accuracy of Meeus ch. 22's short form."""
    T = (jde - 2451545.0) / 36525
    om = 125.04452 - 1934.136261 * T
    L, Lp = 280.4665 + 36000.7698 * T, 218.3165 + 481267.8813 * T
    dpsi = (-17.20 * sind(om) - 1.32 * sind(2 * L) - 0.23 * sind(2 * Lp) + 0.21 * sind(2 * om)) / 3600
    deps = (9.20 * cosd(om) + 0.57 * cosd(2 * L) + 0.10 * cosd(2 * Lp) - 0.09 * cosd(2 * om)) / 3600
    eps0 = 23.4392911 - 0.0130042 * T - 1.64e-7 * T ** 2 + 5.04e-7 * T ** 3
    return dpsi, eps0 + deps


