BASES[("caslon", "round2")] = {'0': 16, '1': 16, '2': 16, '3': 16, '4': 16, '5': 16, '6': 22, '7': 16, '8': 22, '9': 16}


def figure_set(style, screen):
    """The set for a plate's style on a screen, with the 9 made from the 6; None if none is drawn yet."""
    s = SETS.get((style, screen))
    if s is None:
        return None
    s = dict(s)
    if "9" not in s:
        s["9"] = [r[::-1] for r in s["6"][::-1]]
    return s


def baseline(style, screen, ch, rows):
    """Where a figure's baseline falls, rows from its top (lining figures: their foot)."""
    b = BASES.get((style, screen), {})
    if ch == "9" and "9" not in b and "6" in b:          # the 9 is the 6 turned: its baseline mirrored
        return len(rows) - b["6"] + b.get("0", len(rows))
    return b.get(ch, len(rows))


def mask(rows):
    w = max(len(r) for r in rows)
    return np.array([[c == "#" for c in r.ljust(w, ".")] for r in rows])


def compose(style, screen, hh, mm, figures_only=False):
    """The time as a mask: the hour's figures, a small raised h, a space, the minutes, a small raised m. Returns
    (mask, row of the figures' baseline, height of the small figures above it), or None if the set is not drawn. With
    `figures_only`, the same mask with the figures alone (the h and m left out: what the gilding outlines)."""
    s = figure_set(style, screen)
    if s is None:
        return None
    parts = []
    for ch in hh:
        parts.append(("fig", ch))
    parts += [("sup", "h"), ("gap", None)]
    for ch in mm:
        parts.append(("fig", ch))
    parts.append(("sup", "m"))
    figs = [(ch, s[ch]) for kind, ch in parts if kind == "fig"]
    asc = max(baseline(style, screen, ch, rows) for ch, rows in figs)
    desc = max(len(rows) - baseline(style, screen, ch, rows) for ch, rows in figs)
    small = baseline(style, screen, "0", s["0"])                 # the height of the short figures
    widths = []
    for kind, ch in parts:
        widths.append(5 if kind == "gap" else mask(s[ch]).shape[1])
    W = sum(widths) + 2 * (len(parts) - 1)
    out = np.zeros((asc + desc, W), bool)
    x = 0
    for (kind, ch), w in zip(parts, widths):
        if kind == "fig":
            m = mask(s[ch])
            top = asc - baseline(style, screen, ch, s[ch])
        elif kind == "sup":                                       # raised to the top of the short figures
            m = mask(s[ch]) & (not figures_only)
            top = asc - small
        else:
            x += w + 2
            continue
        out[top: top + m.shape[0], x: x + m.shape[1]] |= m
        x += w + 2 if kind != "sup" or ch != "h" else w + 1
    return out, asc, small
