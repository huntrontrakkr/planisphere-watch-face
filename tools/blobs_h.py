"""The face's data blobs (watchface/resources/data/*.bin) as C arrays, for the host harness and the settings page's
preview, which have no resource packs, and the Round 2's outline (proto/screen.py), which the watch has from its
system: build/plan_blobs.h. Standard library only.

    python3 tools/blobs_h.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "watchface" / "resources" / "data"
sys.path.insert(0, str(ROOT / "proto"))
import screen                     # noqa: E402  (standard library only)


def array(name, data):
    rows = [",".join(str(b) for b in data[i: i + 32]) + "," for i in range(0, len(data), 32)]
    return f"static const uint8_t {name}[{len(data)}] __attribute__((aligned(4))) = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    out = ROOT / "build" / "plan_blobs.h"
    out.parent.mkdir(exist_ok=True)
    text = "/* Generated by tools/blobs_h.py from watchface/resources/data; do not edit. */\n#pragma once\n#include <stdint.h>\n"
    for name, file in (("BLOB_PLAN", "plan.bin"), ("BLOB_EMERY", "geom~emery.bin"), ("BLOB_GABBRO", "geom~gabbro.bin"),
                       ("BLOB_FEASTS", "feasts.bin"), ("BLOB_TOOLS", "tools.bin"), ("BLOB_SCENES", "scenes.bin")):
        text += array(name, (DATA / file).read_bytes())
    text += ("/* the Round 2's first lit pixel in each row, top to middle (the rows below mirror them; each row is lit to\n"
             " * 259 minus it): its display's own outline (proto/screen.py) */\n" + array("ROUND2_TOPLEFT", screen.ROUND2_TOPLEFT))
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    main()
